test('panne de recherche et modifications concurrentes préservent les voyages',async({page})=>{
 await seed(page)
 await page.route('**/photon.komoot.io/**',route=>route.abort())
 await page.getByLabel('Une destination ou un lieu').fill('Lazi')
 await page.getByRole('button',{name:'Rechercher',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Connexion au service impossible')
 await expect(page.locator('.discovery-place')).toHaveCount(5)
 await page.locator('.discovery-place').first().click()
 await page.evaluate(key=>{const trips=JSON.parse(localStorage.getItem(key)!);trips.push({id:'other',destination:'Autre voyage',departure:'2027-03-01'});localStorage.setItem(key,JSON.stringify(trips))},key)
 await page.getByRole('button',{name:'Garder cette envie'}).click()
 expect(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).length,key)).toBe(2)
 await page.evaluate(key=>localStorage.setItem(key,'damaged'),key)
 await page.getByRole('button',{name:'Garder cette envie'}).click()
 await expect(page.getByRole('region',{name:'Fiche du lieu'}).getByRole('status')).toContainText('Impossible de lire')
 expect(await page.evaluate(key=>localStorage.getItem(key),key)).toBe('damaged')
})
