test('envie géolocalisée, dédoublonnage, programme daté et sauvegarde ZIP',async({page,browser},info)=>{
 await seed(page)
 await page.getByRole('button',{name:/Chutes de Cambugahay Nature/}).click()
 const detail=page.getByRole('region',{name:'Fiche du lieu'})
 await detail.getByRole('button',{name:'Garder cette envie'}).click()
 await expect(detail.getByRole('status')).toContainText('Envie enregistrée')
 await detail.getByRole('button',{name:'Garder cette envie'}).click()
 await expect(detail.getByRole('status')).toContainText('déjà')
 await detail.getByLabel('Ajouter à une journée').fill('2027-02-09')
 await detail.getByRole('button',{name:'Ajouter à cette journée'}).click()
 await expect(detail.getByRole('status')).toContainText('Étape ajoutée')
 const trips=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),key)
 expect(trips[0].plan.ideas).toHaveLength(1)
 expect(trips[0].plan.ideas[0]).toMatchObject({point:{lat:9.139,lon:123.627},category:'nature'})
 expect(trips[0].plan.stops[0]).toMatchObject({date:'2027-02-09',category:'nature'})
 await detail.getByRole('button',{name:'Fermer la fiche ×'}).click()
 await page.getByRole('button',{name:'Mon voyage',exact:true}).click()
 await page.getByLabel('Mes envies uniquement').check()
 await expect(page.locator('.discovery-place')).toHaveCount(1)
 await page.reload()
 await expect(page.locator('.discovery-place')).toHaveCount(2)
 await page.goto('/#tools')
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Sauvegarder dans Drive'}).click()
 const file=info.outputPath('discovery.zip');await (await pending).saveAs(file)
 const manifest=JSON.parse(new TextDecoder().decode(unzipSync(await readFile(file))['manifest.json']))
 expect(manifest.upcoming.trips[0].plan.ideas[0].point).toEqual({lat:9.139,lon:123.627})
 const freshContext=await browser.newContext(),fresh=await freshContext.newPage()
 await fresh.goto('/#tools');await fresh.getByLabel('Choisir une sauvegarde ZIP').setInputFiles(file)
 await expect(fresh.getByRole('heading',{name:'Restaurer ce carnet ?'})).toBeVisible()
 const safety=fresh.waitForEvent('download');await fresh.getByRole('button',{name:/télécharger la copie de sécurité/i}).click();await (await safety).saveAs(info.outputPath('safety.zip'))
 await fresh.getByRole('checkbox',{name:/je confirme que la copie de sécurité est téléchargée et vérifiée/i}).check()
 await fresh.getByRole('button',{name:'Restaurer ce carnet'}).click()
 await expect(fresh.getByRole('status')).toContainText('restaurées sur cet appareil')
 await fresh.goto('/#explore/test');await expect(fresh.locator('.discovery-place')).toHaveCount(2)
 await freshContext.close()
})
